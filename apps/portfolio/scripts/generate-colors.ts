import { writeFileSync } from "node:fs";

import {
  argbFromHex,
  hexFromArgb,
  Hct,
  SchemeVibrant,
} from "@material/material-color-utilities";

const sources = { cobalt: "#1a73e8", iris: "#4f56c0", ocean: "#0077b6" };
const roles = [
  "primary",
  "onPrimary",
  "primaryContainer",
  "onPrimaryContainer",
  "secondary",
  "onSecondary",
  "secondaryContainer",
  "onSecondaryContainer",
  "tertiary",
  "onTertiary",
  "tertiaryContainer",
  "onTertiaryContainer",
  "surface",
  "onSurface",
  "onSurfaceVariant",
  "surfaceContainerLow",
  "surfaceContainer",
  "surfaceContainerHigh",
  "outline",
  "outlineVariant",
] as const;
const palettes = Object.fromEntries(
  Object.entries(sources).map(([name, seed]) => {
    const scheme = new SchemeVibrant(
      Hct.fromInt(argbFromHex(seed)),
      false,
      0,
      "2025",
      "phone"
    );
    return [
      name,
      Object.fromEntries(
        roles.map((role) => [role, hexFromArgb(scheme[role])])
      ),
    ];
  })
);
const json = (value: unknown): string => JSON.stringify(value, null, 2);
writeFileSync(
  new URL("../src/styles/material.generated.stylex.ts", import.meta.url),
  `// Generated by tokens:generate. Do not edit color roles manually.\nimport * as stylex from '@stylexjs/stylex';\nexport const colors = stylex.defineVars(${json(palettes.cobalt)});\nexport const cobalt = stylex.createTheme(colors, ${json(palettes.cobalt)});\nexport const ocean = stylex.createTheme(colors, ${json(palettes.ocean)});\nexport const iris = stylex.createTheme(colors, ${json(palettes.iris)});\n`
);
writeFileSync(
  new URL("../src/styles/material-palettes.json", import.meta.url),
  `${json({ contrastLevel: 0, generator: "@material/material-color-utilities@0.4.0", isDark: false, palettes, platform: "phone", scheme: "SchemeVibrant", sources, specVersion: "2025" })}\n`
);
